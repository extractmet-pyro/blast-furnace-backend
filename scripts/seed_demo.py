#!/usr/bin/env python
"""Generate every shipped demo artefact (all SYNTHETIC, reproducible from fixed seeds).

  python scripts/seed_demo.py --all              # everything below (~25-40 min CPU)
  python scripts/seed_demo.py --config           # config/plant_config.schema.json + config/demo_bf_config.yaml
  python scripts/seed_demo.py --states [p ...]   # data/demo/initial_state_<preset>.pkl.gz (+ .json meta)
  python scripts/seed_demo.py --rom              # data/demo/rom_<preset>.json (MPC step-response model)
  python scripts/seed_demo.py --history DAYS     # data/demo/history.csv.gz (synthetic plant + twin pipeline)
  python scripts/seed_demo.py --train            # data/models/* hybrid forecasters (DEMO-SYNTHETIC)

Nothing produced here is plant data. Every artefact is labelled SYNTHETIC / DEMO.
"""
from __future__ import annotations

import argparse
import copy
import gzip
import json
import os
import pickle
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
DEMO = ROOT / "data" / "demo"
MODELS = ROOT / "data" / "models"


def log(*a):
    print(time.strftime("%H:%M:%S"), *a, flush=True)


def write_config():
    import jsonschema
    import yaml
    from app.physics.defaults import PRESETS, build_config
    schema = json.loads((ROOT / "config" / "plant_config.schema.json").read_text())
    for p in PRESETS:
        jsonschema.validate(build_config(p), schema)
    cfg = build_config("large_4000")
    hdr = ("# Demo plant configuration - 'Industry-X' large BF (~4000 m3 working volume)\n"
           "# ILLUSTRATIVE DEMO VALUES - not certified for any facility. Replace every value with site data\n"
           "# before calibration. Validated against config/plant_config.schema.json (PUT /api/v1/config/plant).\n"
           "# Generated by scripts/seed_demo.py from app/physics/defaults.py (preset large_4000).\n")
    (ROOT / "config" / "demo_bf_config.yaml").write_text(hdr + yaml.safe_dump(cfg, sort_keys=False, width=120))
    log("config artefacts validated/written")


def make_states(presets):
    from app.core.config import MODEL_VERSION
    from app.physics import outputs as out
    from app.physics.defaults import build_config
    from app.physics.integrator import BlastFurnaceModel
    from app.ml.registry import file_sha256
    from app.services.twin_service import cfg_hash, physics_hash
    DEMO.mkdir(parents=True, exist_ok=True)
    for p in presets:
        t0 = time.time()
        cfg = build_config(p)
        m = BlastFurnaceModel(cfg)
        m.warm_start(hours=36.0)
        traj = []
        for _ in range(10):
            m.run(3.0)
            k = out.kpis(m)
            traj.append({kk: round(k[kk]["value"], 4) for kk in ("hmt_C", "hm_si_pct", "production_t_d", "fuel_rate_kg_tHM",
                                                                 "eta_CO_pct", "pressure_drop_kPa", "top_gas_T_C")})
        if out.balances(m)["step"]["status"] != "OK":
            raise SystemExit(f"{p}: balance check failed - not shipping state")
        with gzip.open(DEMO / f"initial_state_{p}.pkl.gz", "wb", compresslevel=6) as f:
            pickle.dump(m, f, protocol=pickle.HIGHEST_PROTOCOL)
        meta = {"preset": p, "cfg_sha256": cfg_hash(cfg), "physics_sha256": physics_hash(cfg), "model_version": MODEL_VERSION,
                "file_sha256": file_sha256(DEMO / f"initial_state_{p}.pkl.gz"),
                "simulated_h": m.t / 3600.0,
                "created_utc": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"), "label": "SYNTHETIC demo state",
                "kpi_last_30h_every_3h": traj}
        (DEMO / f"initial_state_{p}.json").write_text(json.dumps(meta, indent=1))
        log(f"state {p}: t={m.t / 3600:.0f} h, last {traj[-1]} ({time.time() - t0:.0f} s)")


def make_rom(preset="large_4000"):
    from app.physics.integrator import BlastFurnaceModel
    from app.mpc.predictions import identify
    with gzip.open(DEMO / f"initial_state_{preset}.pkl.gz", "rb") as f:
        m: BlastFurnaceModel = pickle.load(f)
    t0 = time.time()
    rom = identify(m, Ts_s=900.0, horizon_h=12.0, progress=lambda p, msg: log(f"  identify {p * 100:.0f}% {msg}"))
    d = rom.as_dict()
    (DEMO / f"rom_{preset}.json").write_text(json.dumps(d))
    G = rom.gain()
    log(f"ROM identified in {time.time() - t0:.0f} s; gains (per unit MV):")
    for i, c in enumerate(rom.cvs):
        log("   ", c, {mv: round(float(G[i, j]), 4) for j, mv in enumerate(rom.mvs)})


def make_history(days: float, preset="large_4000", seed=5):
    """Run the full live pipeline (synthetic plant -> sensors -> quality -> twin -> observer) with
    rule-based 'operator' moves and a few instrument faults; write the merged history frame."""
    import numpy as np
    import pandas as pd
    tmp = tempfile.mkdtemp(prefix="bfseed_")
    os.environ["DATA_DIR"] = tmp
    os.environ["DATABASE_URL"] = f"sqlite:///{tmp}/seed.db"
    os.environ["SIM_AUTOSTART"] = "false"
    os.environ["PLANT_PRESET"] = preset
    from app.core.config import get_settings
    get_settings.cache_clear()
    from app.data.synthetic import FaultSpec
    from app.db.session import init_db
    from app.services.twin_service import TwinService
    init_db()
    svc = TwinService()
    svc.persist_samples = False
    svc.ml_models = {}
    svc.start(background=False)
    svc.ml_models, svc.ml_meta = {}, {}          # history must not depend on previously trained models
    assert svc.state == "RUNNING", svc.state_msg
    rng = np.random.default_rng(seed)
    lim = svc.cfg["equipment_limits"]
    h0 = svc.plant.model.t / 3600.0
    for kind, tag, mag, start, dur in (("DRIFT", "TG_CO2", 0.4, 60, 8), ("STUCK", "HTC_SUMP", 0.0, 110, 6),
                                       ("DROPOUT", "TG_PRESS", 0.0, 170, 2), ("BIAS", "BL_TEMP", 15.0, 230, 5)):
        if start < days * 24:
            svc.plant.faults.append(FaultSpec(kind, tag, mag, h0 + start, h0 + start + dur))
    n = int(days * 86400 / svc.twin.dt)
    rows = []
    next_move = 3600 * 4
    last_hmt = None
    base_coke = svc.setpoints["coke_batch_t"]
    t_start = time.time()
    for i in range(n):
        t_rel = i * svc.twin.dt
        if t_rel >= next_move:
            sp = svc.setpoints
            # thermal policy (operator heuristic on the last dip temperature) + random exploration moves
            if last_hmt is not None and last_hmt < 1478:
                ch = {"coke_batch_t": round(min(sp["coke_batch_t"] * 1.012, base_coke * 1.06), 3)}
            elif last_hmt is not None and last_hmt > 1528:
                ch = {"coke_batch_t": round(max(sp["coke_batch_t"] * 0.990, base_coke * 0.95), 3)}
            else:
                mv = rng.choice(["blast_temp_C", "pci_t_h", "o2_enrichment_pct", "blast_moisture_g_Nm3", "blast_volume_Nm3_min",
                                 "coke_batch_t"])
                step = {"blast_temp_C": 25.0, "pci_t_h": 4.0, "o2_enrichment_pct": 0.5, "blast_moisture_g_Nm3": 4.0,
                        "blast_volume_Nm3_min": 0.025 * sp["blast_volume_Nm3_min"], "coke_batch_t": 0.012 * sp["coke_batch_t"]}[mv]
                v = sp[mv] + float(rng.choice([-1, 1])) * step
                if mv in lim:
                    lo, hi = lim[mv]
                    span = hi - lo
                    v = float(np.clip(v, lo + 0.15 * span, hi - 0.15 * span))
                if mv == "coke_batch_t":
                    v = float(np.clip(v, base_coke * 0.96, base_coke * 1.05))
                ch = {mv: round(v, 3)}
            try:
                svc.setpoints.update(ch)
            except Exception:
                pass
            next_move = t_rel + 3600 * float(rng.uniform(3.0, 6.0))
        svc.tick()
        tel = dict(svc.telemetry[-1])
        tw = svc.twin_hist[-1]
        for k, v in tw.items():
            if k not in ("t_s", "t_utc"):
                tel["phys_" + ("si_pct" if k == "hm_si_pct" else k)] = v
        if tel.get("HMT_DIP") is not None:
            last_hmt = tel["HMT_DIP"]
        rows.append(tel)
        if i % 720 == 0:
            el = time.time() - t_start
            log(f"history day {t_rel / 86400:.1f}/{days}  HMT(phys)={tw['hmt_C']:.0f}  Si={tw['hm_si_pct']:.2f}  "
                f"theta={np.round(svc.ekf.theta, 3).tolist()}  {el:.0f}s")
    df = pd.DataFrame(rows)
    df.insert(2, "data_origin", "SYNTHETIC")
    DEMO.mkdir(parents=True, exist_ok=True)
    df.to_csv(DEMO / "history.csv.gz", index=False, compression="gzip", float_format="%.6g")
    meta = {"rows": len(df), "days": days, "preset": preset, "seed": seed, "columns": list(df.columns),
            "label": "SYNTHETIC history from the Industry-X demo plant (hidden-truth plant model + sensor layer); "
                     "phys_* columns are twin virtual sensors; <TAG>__q quality flags; <TAG>__t_sample lab sampling time.",
            "faults_injected": [vars(f) for f in svc.plant.faults], "created_utc": datetime.now(timezone.utc).isoformat()}
    (DEMO / "history_meta.json").write_text(json.dumps(meta, indent=1, default=str))
    log(f"history written: {len(df)} rows, {len(df.columns)} columns")


def train():
    import pandas as pd
    from app.ml.registry import ModelRegistry
    from app.ml.training import train_all
    import shutil
    df = pd.read_csv(DEMO / "history.csv.gz")
    if MODELS.exists():
        shutil.rmtree(MODELS)
    reg = ModelRegistry(MODELS)
    res = train_all(df, reg, "SYNTHETIC")
    for r in res:
        if r["status"] != "TRAINED":
            log("untrained:", r)
            continue
        t = r["metrics"]["test"]
        log(f"{r['model_id']}: test RMSE hybrid={t['hybrid']['RMSE']:.3f} physics={t['physics_only']['RMSE']:.3f} "
            f"persistence={t['persistence']['RMSE']:.3f} arx={t['arx_ridge']['RMSE']:.3f} cover95={t['interval95_coverage']:.2f} "
            f"beats={r['beats_baselines_on_test']}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--config", action="store_true")
    ap.add_argument("--states", nargs="*")
    ap.add_argument("--rom", action="store_true")
    ap.add_argument("--history", type=float)
    ap.add_argument("--train", action="store_true")
    a = ap.parse_args()
    from app.physics.defaults import PRESETS
    if a.all or a.config:
        write_config()
    if a.all or a.states is not None:
        make_states(a.states or list(PRESETS))
    if a.all or a.rom:
        make_rom()
    if a.all or a.history:
        make_history(a.history or 12.0)
    if a.all or a.train:
        train()


if __name__ == "__main__":
    main()
